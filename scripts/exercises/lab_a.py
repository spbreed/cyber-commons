"""Function A as a hands-on lab: every step runs in the reader's browser.

Students said Function A was too much to read with no hands-on time before the
first command worked. This is the other way in: one page, a play button, and
each step is real Python run against the real CyberTravels code — the tree
exactly as it stood at the end of that lesson, from `checkpoint.py`. Nothing
here is a recording of a run. Python runs in the browser (Pyodide), so the
output a reader sees is the output the code produced, and if it cannot start
the page says so rather than showing what it would have printed.

**The model is the reader.** No step asks a model anything, because a page that
showed a canned model answer would be the substitute this repository refuses
everywhere else. Where a lesson is about what the model proposes, the reader
types the proposal and the code decides — which is the lesson's own sentence,
"the model proposes, your code decides", done with their hands.

Every `expect` was produced by running the code, and `build_lab.py --check`
runs every step again with CPython at the lesson's checkpoint and fails if the
output drifts. A step whose output depends on the machine (a Python version)
sets `expect` to None and is only required to run.

Per lesson: `goal` (one plain sentence), `actors` (up to four lanes for the
diagram), and `steps`. Per step: `title`, `arrow` (from, to, label — the lane
names), `say` (two to four short lines), and either `code` (run here) or `cmd`
(for the reader's own terminal; shown with a copy button, never run).
"""

